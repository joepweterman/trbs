"""
Human-readable rendering of the confirmatory analysis.

Kept separate from ``analyze_study.py`` so that the module which computes the
numbers is not also the module which formats them; the report is built from a
completed analysis and never recomputes anything itself.
"""

from __future__ import annotations

from math import isfinite

import pandas as pd


def _fmt(value, digits: int = 3) -> str:
    """
    Format a possibly-missing statistic.
    :param value: the number to format
    :param digits: decimal places
    :return: the formatted value, or a dash when it does not exist
    """
    return "--" if not isfinite(value) else f"{value:.{digits}f}"


class StudyReport:  # pylint: disable=too-few-public-methods
    """
    Renders the results summary of a completed :class:`StudyAnalysis`.

    :param analysis: the analysis whose summary and frame are reported
    """

    def __init__(self, analysis):
        self.analysis = analysis
        self.df = analysis.df
        self.meta = analysis.meta
        self.summary = analysis.summary

    def _header(self) -> list:
        """The provenance block and the decision-basis note."""
        return [
            "# Confirmatory study - results summary",
            "",
            "Generated by `analyze_study.py` from the frozen results store; do not edit by hand.",
            "",
            f"- Rows: **{len(self.df)}** ({int(self.df.censored.sum())} censored)",
            f"- Generated at vlinder commit `{self.meta.get('vlinder_commit', '?')}`",
            f"- Recovery threshold: gap <= {self.analysis.recovery_eps} appreciation points; "
            f"primary scenario {self.analysis.primary_scenario}",
            "",
            "## Hypothesis decisions (pre-registration section 4)",
            "",
            "> **Decision basis.** Section 4 states the H1 rule on *pooled* recovery, and it is read here as pooling",
            "> each case's three scenarios (n = 90 per variant x k). This is not a free choice: at the per-cell",
            "> n = 30 of the descriptive table, flawless 30/30 recovery still yields a Wilson lower bound of only",
            '> 0.886, so a ">= 0.95" rule would be unreachable for every method regardless of performance. Under',
            "> the pooled reading perfect recovery clears the bar at 0.959 and the rule discriminates as intended.",
            "",
            "| ID | Verdict | Key evidence |",
            "|---|---|---|",
        ]

    @staticmethod
    def _evidence(hid: str, block: dict) -> str:
        """
        One line of evidence behind a verdict.
        :param hid: hypothesis id
        :param block: the verdict entry
        :return: the evidence sentence
        """
        if hid.startswith("H1"):
            return (
                f"min recovery {block['min_recovery']:.3f}, "
                f"worst Wilson lower bound {block['min_ci_low']:.3f} at k={block['worst_k']}"
            )
        if hid == "H2":
            return (
                f"grid censored at k={block['grid_censored_at_k']}, "
                f"recovery at the largest k is {block['grid_recovery_at_max_k']:.3f}"
            )
        ci_low, ci_high = block["slsqp_evals_loglog_ci"]
        return (
            f"clause 1 holds: grid runtime x{block['grid_runtime_factor_per_lever']:.2f} per lever vs "
            f"SLSQP x{block['slsqp_runtime_factor_per_lever']:.2f}. clause 2 "
            f"{'holds' if block['clause_2_slsqp_evals_linear_in_k'] else 'fails'}: SLSQP evaluation exponent "
            f"{block['slsqp_evals_loglog_exponent']:.2f} (95% CI [{ci_low:.2f}, {ci_high:.2f}], "
            f"linear growth would be 1)"
        )

    def _recovery_section(self, recovery: pd.DataFrame) -> list:
        """Recovery per method and k, plus the oracle-tightness note."""
        ks = sorted(self.df.k.unique())
        out = [
            "",
            "## Recovery by method (pooled over scenarios and both variants)",
            "",
            "| Method | " + " | ".join(f"k={k}" for k in ks) + " |",
            "|---|" + "---|" * len(ks),
        ]
        for method in self.analysis.method_order:
            sub = recovery[recovery.method == method]
            cells = []
            for k in ks:
                rows = sub[sub.k == k]
                cells.append(f"{rows.recovered.sum() / rows.n.sum():.3f}" if rows.n.sum() else "-")
            out.append(f"| {self.analysis.method_labels[method]} | " + " | ".join(cells) + " |")

        tight = self.summary["oracle_tightness"]
        out += [
            "",
            "## Oracle tightness",
            "",
            f"- Cells exceeding the certified optimum beyond 1e-6: **{tight['n_beyond_noise_1e-6']}** "
            f"({tight['share_beyond_noise']:.2%} of evaluated cells)",
            f"- Largest exceedance: **{tight['largest_exceedance']:.2e}** appreciation points, "
            f"i.e. {self.analysis.recovery_eps / tight['largest_exceedance']:.0f}x below the recovery threshold",
        ]
        return out

    def _scaling_section(self, scaling: pd.DataFrame) -> list:
        """The scaling regressions and the specification note."""
        out = [
            "",
            "## Scaling regressions (OLS, HC3 standard errors)",
            "",
            "| Spec | Response | Method | Slope | HC3 SE | 95% CI | R2 |",
            "|---|---|---|---|---|---|---|",
        ]
        for row in scaling.itertuples():
            interval = "--" if not isfinite(row.ci_low) else f"[{row.ci_low:.3f}, {row.ci_high:.3f}]"
            note = f" {row.note}" if row.note else ""
            out.append(
                f"| {row.spec} | {row.response} | {self.analysis.method_labels[row.method]} | "
                f"{_fmt(row.slope_per_lever)} | {_fmt(row.se_hc3)} | {interval} | {_fmt(row.r_squared)}{note} |"
            )
        out += [
            "",
            "> The baseline's runtime slope is a lower bound: its most expensive cells are censored out of the "
            "regression (amendment A1).",
            "",
            "> `semilog_preregistered` is the section 4 specification, log(y) on k, whose slope is a growth rate "
            "per added lever. `loglog_supplementary` regresses log(y) on log(k) and is **not** pre-registered; it "
            "is reported only because H5's second clause is stated as growth that is linear in k, which is a claim "
            "about an exponent and cannot be read off a semi-log slope.",
        ]
        return out

    @staticmethod
    def _paired_section(paired: pd.DataFrame) -> list:
        """The Holm-corrected paired comparisons."""
        out = [
            "",
            "## Paired Wilcoxon signed-rank vs SLSQP (Holm-corrected across k)",
            "",
            "| Comparison | k | Pairs | Median gap difference | p (Holm) |",
            "|---|---|---|---|---|",
        ]
        for row in paired.itertuples():
            pairs = "0 (all censored)" if row.n_pairs == 0 else str(row.n_pairs)
            median = "--" if row.n_pairs == 0 else f"{row.median_gap_diff:.2e}"
            out.append(f"| {row.comparison} | {row.k} | {pairs} | {median} | {row.p_holm:.3g} |")
        out += [
            "",
            "> A significant test with a median difference of order 1e-08 points is a consistent sign, not a "
            "meaningful margin: the pre-registered test detects direction, and the median difference column is "
            "what carries the magnitude.",
        ]
        return out

    def render(self, recovery: pd.DataFrame, scaling: pd.DataFrame, paired: pd.DataFrame) -> str:
        """
        Build the full report.
        :param recovery: the pooled recovery table
        :param scaling: the scaling regression table
        :param paired: the paired-comparison table
        :return: the markdown document
        """
        out = self._header()
        for hid in ("H1a", "H1b", "H2", "H5"):
            block = self.summary["hypotheses"][hid]
            out.append(f"| {hid} | **{block['verdict']}** | {self._evidence(hid, block)} |")
        out += self._recovery_section(recovery)
        out += self._scaling_section(scaling)
        out += self._paired_section(paired)
        out += [
            "",
            "## Files",
            "",
            "- `figures/fig1_recovery_vs_k.(png|pdf)`",
            "- `figures/fig2_scaling_vs_k.(png|pdf)`",
            "- `figures/fig3_gap_distribution.(png|pdf)`",
            "- `tables/recovery.tex`, `tables/scaling.tex`, `tables/paired_wilcoxon.tex`",
            "",
        ]
        return "\n".join(out)
