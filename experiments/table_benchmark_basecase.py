"""
This file rewrites the two packaged-case tables of the results chapter from the stored
benchmark, after the review round of 8 September 2026.

The first version of the benchmark table averaged appreciation and gap over each case's
three scenarios and printed the gap in scientific notation, which made Beerwiser read
71.67 in one table and 65.71 in every other, and put solver tolerance (1e-6) and a
missed basin (4.1) in the same column. This file renders the base-case scenario per case
with four decimals, the other scenarios in a separate appendix table, and measures every
run against the best value found in *any* study of the thesis on that cell (the
benchmark, the A4 packaged half, the timed and the evaluation-budget sweeps), which is
looser than a certificate but tighter than the best of one run. The shadow-price table
drops its constant "binding" column and gains the one-sided price for one percent less
budget, which the text discusses.

Run (reads the stores, runs nothing):
  python experiments/table_benchmark_basecase.py
"""

import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
REAL = HERE / "out" / "real_cases"
TIMED = HERE / "out" / "time_limited"
A4 = HERE / "synthetic" / "generated" / "study" / "results_equalfooting.jsonl"

CASES = ("Beerwiser", "Refugee", "IZZ")
METHODS = ("grid", "slsqp", "basin_hopping", "genetic_algorithm")
LABELS = {
    "grid": "Grid (baseline)",
    "slsqp": "SLSQP multi-start",
    "basin_hopping": "Basin-hopping",
    "genetic_algorithm": "Genetic algorithm",
}


def best_known():
    """
    This function collects the best appreciation seen on every (case, scenario) cell
    across the thesis's packaged-case studies.
    :return: a dict keyed by (case, scenario)
    """
    seen = {}

    def note(frame, case_col, scenario_col):
        for (case, scenario), value in frame.groupby([case_col, scenario_col])["appreciation"].max().items():
            seen[(case, scenario)] = max(seen.get((case, scenario), float("-inf")), float(value))

    note(pd.read_csv(REAL / "benchmark.csv"), "case", "scenario")
    for name in ("time_limited_comparison_v2.csv", "eval_limited_comparison.csv"):
        if (TIMED / name).exists():
            note(pd.read_csv(TIMED / name), "case", "scenario")
    if A4.exists():
        with A4.open(encoding="utf-8") as handle:
            rows = [json.loads(line) for line in handle if line.strip()]
        packaged = pd.DataFrame([row for row in rows if row["family"] == "packaged"])
        if len(packaged):
            note(packaged.rename(columns={"f_found": "appreciation"}), "case_name", "scenario")
    return seen


def base_case_of(frame, case):
    """The first scenario of a case in the benchmark, which is its base case."""
    return frame[frame.case == case].scenario.iloc[0]


def table_base_case(frame, reference):
    """
    This function renders the base-case benchmark table.
    :param frame: the benchmark rows
    :param reference: the best known value per cell
    :return: the table as a string
    """
    lines = [
        "% Generated by table_benchmark_basecase.py - do not edit by hand.",
        r"\begin{tabular}{llrrr}",
        r"\toprule",
        r"Case & Method & Appreciation & Below best known & Time (s) \\",
        r"\midrule",
    ]
    for case in CASES:
        scenario = base_case_of(frame, case)
        sub = frame[(frame.case == case) & (frame.scenario == scenario)]
        for i, method in enumerate(METHODS):
            cell = sub[sub.method == method]
            if cell.empty:
                continue
            row = cell.iloc[0]
            below = reference[(case, scenario)] - row.appreciation
            lines.append(
                f"{case if i == 0 else ''} & {LABELS[method]} & {row.appreciation:.4f} & "
                f"{below:.4f} & {row.wall_time_s:.1f} \\\\"
            )
        lines.append(r"\addlinespace")
    lines[-1] = r"\bottomrule"
    lines.append(r"\end{tabular}")
    return "\n".join(lines) + "\n"


def table_all_scenarios(frame, reference):
    """
    This function renders the appendix table with every scenario.
    :param frame: the benchmark rows
    :param reference: the best known value per cell
    :return: the table as a string
    """
    lines = [
        "% Generated by table_benchmark_basecase.py - do not edit by hand.",
        r"\begin{tabular}{lllrrr}",
        r"\toprule",
        r"Case & Scenario & Method & Appreciation & Below best known & Time (s) \\",
        r"\midrule",
    ]
    for case in CASES:
        first_row = True
        for scenario in frame[frame.case == case].scenario.unique():
            sub = frame[(frame.case == case) & (frame.scenario == scenario)]
            for i, method in enumerate(METHODS):
                cell = sub[sub.method == method]
                if cell.empty:
                    continue
                row = cell.iloc[0]
                below = reference[(case, scenario)] - row.appreciation
                lines.append(
                    f"{case if first_row else ''} & {scenario if i == 0 else ''} & {LABELS[method]} & "
                    f"{row.appreciation:.4f} & {below:.4f} & {row.wall_time_s:.1f} \\\\"
                )
                first_row = False
        lines.append(r"\addlinespace")
    lines[-1] = r"\bottomrule"
    lines.append(r"\end{tabular}")
    return "\n".join(lines) + "\n"


def table_shadow(shadow):
    """
    This function renders the shadow-price table with both one-sided prices.
    :param shadow: the shadow-price rows
    :return: the table as a string
    """
    lines = [
        "% Generated by table_benchmark_basecase.py - do not edit by hand.",
        r"\begin{tabular}{llrrr}",
        r"\toprule",
        r"Case & Scenario & Spend & Points per +1\% budget & Points per $-$1\% budget \\",
        r"\midrule",
    ]
    for row in shadow.itertuples():
        lines.append(
            f"{row.case} & {row.scenario} & {row.spend_fraction:.3f} & "
            f"{row.points_per_1pct_budget_up:+.4f} & {row.points_per_1pct_budget_down:+.4f} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def main():
    """Write the three tables next to the benchmark store."""
    frame = pd.read_csv(REAL / "benchmark.csv")
    reference = best_known()
    target = REAL / "tables"
    target.mkdir(parents=True, exist_ok=True)
    written = {
        "benchmark_basecase.tex": table_base_case(frame, reference),
        "benchmark_all_scenarios.tex": table_all_scenarios(frame, reference),
        "shadow_prices_two_sided.tex": table_shadow(pd.read_csv(REAL / "shadow_prices.csv")),
    }
    for name, content in written.items():
        (target / name).write_text(content, encoding="utf-8")
        print(f"[table] written to {target / name}")
    for (case, scenario), value in sorted(reference.items()):
        print(f"  best known {case:<10} {scenario:<20} {value:.4f}")


if __name__ == "__main__":
    main()
